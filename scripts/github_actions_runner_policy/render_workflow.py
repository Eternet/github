#!/usr/bin/env python3
"""Render the single shared, path-filtered runner-policy workflow contract."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys

WORKFLOW_PATH = '.github/workflows/self-hosted-runner-policy.yml'
ACTION = 'Eternet/github/scripts/github_actions_runner_policy'
CONFIGS = ('.github/actionlint.yaml', '.github/actionlint.yml', '.actionlint.yaml', '.actionlint.yml')


def render(root: Path, default_branch: str, policy_ref: str | None, central: bool = False) -> str:
    if not re.fullmatch(r'[A-Za-z0-9_./-]+', default_branch) or '..' in default_branch:
        raise ValueError('A literal default branch is required.')
    if not central and not re.fullmatch(r'[a-f0-9]{40}', policy_ref or ''):
        raise ValueError('Use an integrated immutable 40-character policy commit.')
    paths = ['.github/workflows/**', '.github/actions/**']
    paths.extend(path for path in CONFIGS if (root / path).is_file())
    if central:
        paths.append('scripts/github_actions_runner_policy/**')
    filters = '\n'.join('      - ' + json.dumps(path) for path in paths)
    action = './scripts/github_actions_runner_policy' if central else ACTION + '@' + policy_ref
    text = f'''# Generated by scripts/github_actions_runner_policy/render_workflow.py in Eternet/github.
name: Self-hosted runner policy

on:
  pull_request:
    paths:
{filters}
  push:
    branches: [{json.dumps(default_branch)}]
    paths:
{filters}
  workflow_dispatch:

permissions:
  contents: read

concurrency:
  group: runner-policy-${{{{ github.event.pull_request.number || github.ref }}}}
  cancel-in-progress: true

jobs:
  runner-policy:
    runs-on: [self-hosted, Linux]
    timeout-minutes: 5
    steps:
      - uses: actions/checkout@v4
        with:
          persist-credentials: false
      - uses: {action}
'''
    if central:
        text += '''      - name: Verify policy and trigger regression cases
        shell: bash
        run: |
          set -euo pipefail
          policy_venv="$(mktemp -d "$RUNNER_TEMP/runner-policy-tests.XXXXXXXX")"
          trap 'rm -rf -- "$policy_venv"' EXIT
          python -m venv "$policy_venv"
          "$policy_venv/bin/python" -m pip install --disable-pip-version-check --only-binary=:all: PyYAML==6.0.3
          "$policy_venv/bin/python" -m unittest discover -s scripts/github_actions_runner_policy -p 'test_*.py' -v
          "$policy_venv/bin/python" -m unittest discover -s .github/actions/verify-dotnet-readiness/tests -p 'test_*.py' -v
'''
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, required=True)
    parser.add_argument('--default-branch', required=True)
    parser.add_argument('--policy-ref')
    parser.add_argument('--central', action='store_true')
    operation = parser.add_mutually_exclusive_group()
    operation.add_argument('--write', action='store_true')
    operation.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        content = render(args.root, args.default_branch, args.policy_ref, args.central)
        target = args.root / WORKFLOW_PATH
        if args.check:
            if not target.is_file() or target.read_text(encoding='utf-8-sig') != content:
                print(f'Workflow differs from central template: {target}', file=sys.stderr)
                return 1
        elif args.write:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding='utf-8', newline='\n')
        else:
            print(content, end='')
    except (OSError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
